/**
 * Coherent, deterministic FP&A fixture for the Financial Statements showcase.
 *
 * GRAIN & INVARIANTS (read before editing):
 * - Facts are monthly. `period` is an ISO `YYYY-MM` key; each maps to a month-end date.
 * - Fiscal year == calendar year (fyStartMonth = 1). Documented so YTD/QTD/FY are unambiguous.
 * - `AS_OF` is the reporting anchor. Months <= AS_OF have Actuals (AC); months after AS_OF
 *   are forecast-only (AC is absent, FC carries the outlook). Budget (BU) exists for all
 *   in-year months (an annual plan). Prior Year (PY) is NOT a scenario — it is derived by
 *   looking up the SAME line's AC exactly 12 months earlier (see statement-model.ts).
 * - Revenue reconciles to the product driver facts: Revenue(period,scenario) ==
 *   Σ products units*price. This keeps the PVM (price/volume/mix) bridge internally
 *   consistent with the P&L.
 * - Cost lines are stored as POSITIVE magnitudes with `sign: -1` in the row model, so a
 *   single rollup can subtotal them; presentation flips the sign. Never store negative here.
 * - Working-capital + capex facts (`wcFacts`) are the explicit, reconciled inputs the
 *   indirect cash-flow statement is built from — cash flow is NOT re-derived from the P&L.
 *
 * Everything is generated by a seeded PRNG so the dataset is byte-stable across builds
 * (no Math.random, no Date.now) — required for deterministic snapshot tests.
 */

export type Scenario = "AC" | "BU" | "FC";

export interface FiscalCalendar {
  /** 1 = January. Calendar-aligned fiscal year for this demo dataset. */
  fyStartMonth: number;
}

export const CALENDAR: FiscalCalendar = { fyStartMonth: 1 };

/** Two full calendar years of monthly periods: 2023-01 .. 2024-12. */
export const START_YEAR = 2023;
export const YEARS = 2;

/** Reporting anchor: Actuals are closed through this month-end. */
export const AS_OF = "2024-08";

export const CURRENCIES = ["USD", "EUR", "GBP"] as const;
export type CurrencyCode = (typeof CURRENCIES)[number];
export const BASE_CURRENCY: CurrencyCode = "USD";

/** All monthly period keys in order, e.g. "2023-01". */
export const PERIODS: string[] = (() => {
  const out: string[] = [];
  for (let y = 0; y < YEARS; y++) {
    for (let m = 1; m <= 12; m++) {
      out.push(`${START_YEAR + y}-${String(m).padStart(2, "0")}`);
    }
  }
  return out;
})();

/** Month-end ISO date for a period key (used for date-based period filtering). */
export function periodEndDate(period: string): string {
  const [y, m] = period.split("-").map(Number);
  const end = new Date(y, m, 0); // day 0 of next month = last day of this month
  return end.toISOString().slice(0, 10);
}

/** True when a period is actualised (<= AS_OF). */
export function isActualPeriod(period: string): boolean {
  return period <= AS_OF;
}

