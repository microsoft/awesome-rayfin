"""Publish the Power BI twin `Caldova Finance (Power BI)` (fabric/caldova-finance.Report) on the model (idempotent).

The report is generated by dwg cli from dwg/caldova-finance.json (README, "Power BI twin"): the same three pages
as the app's original-visual view, with Michael Tenner's P&L Statement byDatenWG 1.7 registered in the report.
Locally the report points at the model folder (byPath); published, it binds to the model by id (byConnection).

Usage:  python tools/fabric/publish_report.py
"""
from __future__ import annotations

import base64
import json

from fabric_api import ROOT, api, config, guard, save_config

REPORT_DIR = ROOT / "fabric" / "caldova-finance.Report"


def parts(ws: str, model_name: str, model_id: str) -> list[dict]:
    out = []
    for f in sorted(p for p in REPORT_DIR.rglob("*") if p.is_file()):
        rel = f.relative_to(REPORT_DIR).as_posix()
        if rel == ".platform":
            continue
        raw = f.read_bytes()
        if rel == "definition.pbir":
            pbir = json.loads(raw)
            pbir["datasetReference"] = {"byConnection": {"connectionString": (
                f'Data Source="powerbi://api.powerbi.com/v1.0/myorg/{ws}";initial catalog={model_name};'
                f"integrated security=ClaimsToken;semanticmodelid={model_id}")}}
            raw = json.dumps(pbir, indent=2).encode("utf-8")
        out.append({"path": rel, "payload": base64.b64encode(raw).decode("ascii"), "payloadType": "InlineBase64"})
    return out


def main() -> None:
    cfg = config()
    ws, model_id, name = cfg["workspaceId"], cfg["modelId"], cfg.get("reportName", "Caldova Finance (Power BI)")
    guard(ids=[ws, model_id], names=[name])
    definition = {"parts": parts(ws, cfg["modelName"], model_id)}
    _, listing, _ = api("GET", f"/workspaces/{ws}/reports")
    existing = next((r for r in listing.get("value", []) if r["displayName"] == name), None)
    if existing:
        # Only a report this tool created (id recorded) is overwritten; a same-named stranger is left alone.
        if (cfg.get("reportId") or "").lower() != existing["id"].lower():
            raise SystemExit(f"a report named {name} exists that this tool did not record: nothing written")
        guard(ids=[existing["id"]])
        print(f"updating {name} ({existing['id']})")
        api("POST", f"/workspaces/{ws}/reports/{existing['id']}/updateDefinition", {"definition": definition})
        report_id = existing["id"]
    else:
        print(f"creating {name}")
        api("POST", f"/workspaces/{ws}/reports", {
            "displayName": name, "definition": definition,
            "description": "Caldova Finance as a Power BI report: the three statements in the P&L Statement byDatenWG visual (dwg cli).",
        })
        _, listing, _ = api("GET", f"/workspaces/{ws}/reports")
        report_id = next(r["id"] for r in listing["value"] if r["displayName"] == name)
        cfg["reportId"] = report_id
        save_config(cfg)
    print(f"  report id recorded in target.json; open: https://app.fabric.microsoft.com/groups/{ws}/reports/{report_id}?ctid={cfg['tenantId']}")


if __name__ == "__main__":
    main()
